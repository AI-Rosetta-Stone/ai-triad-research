#!/usr/bin/env node
/**
 * scripts/build-lessons-index.mjs: generate docs/lessons/INDEX.md from docs/LessonsLearned.md
 *
 * Problem: LessonsLearned.md is ~1.1 MB. Agents that need one entry should not load the
 * whole file. The physical split is deferred (the file is actively appended to), so this
 * script emits a one-line-per-entry index with line ranges instead.
 *
 * Deterministic and idempotent: same input, byte-identical output. No dependencies.
 * Exit 0 = index written. Exit 1 = source file missing or unreadable.
 */

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = resolve(ROOT, 'docs/LessonsLearned.md');
const OUTPUT = resolve(ROOT, 'docs/lessons/INDEX.md');

const HEADING = /^## (.*)$/;
const NUMBER = /^#(\d+)\s+/;
const CATEGORY = /^\[([^\]]+)\]\s*/;

/** Parse the markdown into entries with 1-based inclusive line ranges. */
export function parseEntries(text) {
  const lines = text.split(/\r?\n/);
  // A trailing newline yields a final empty segment that is not a real line.
  if (lines.length > 0 && lines[lines.length - 1] === '') lines.pop();
  const heads = [];
  let inFence = false;
  lines.forEach((line, i) => {
    if (/^\s*(```|~~~)/.test(line)) inFence = !inFence;
    if (inFence) return;
    const m = HEADING.exec(line);
    if (m) heads.push({ line: i + 1, raw: m[1].trim() });
  });
  return heads.map((h, idx) => {
    let rest = h.raw;
    let number = null;
    let category = null;
    const n = NUMBER.exec(rest);
    if (n) { number = n[1]; rest = rest.slice(n[0].length); }
    const c = CATEGORY.exec(rest);
    if (c) { category = c[1]; rest = rest.slice(c[0].length); }
    const end = idx + 1 < heads.length ? heads[idx + 1].line - 1 : lines.length;
    return { number, category, title: rest.trim(), start: h.line, end };
  });
}

// Escape table pipes as \| (GFM honours it even inside code spans). '\|' would be just '|' (t/226).
const cell = (s) => s.replace(/\|/g, '\\|');

export function renderIndex(entries) {
  const out = [
    '# Lessons Learned Index',
    '',
    '<!-- GENERATED by scripts/build-lessons-index.mjs (npm run lessons:index). Do not edit by hand. -->',
    '',
    'One line per entry in `docs/LessonsLearned.md`. Do not open that file whole (about 1 MB). Grep this index for a keyword, number or category, then read just that entry by line range: `sed -n \'START,ENDp\' docs/LessonsLearned.md`. Line ranges are inclusive and refer to the file as of the last index build; if an entry looks cut off, rebuild with `npm run lessons:index`.',
    '',
    '| # | Category | Title | Lines |',
    '|---|---|---|---|',
  ];
  for (const e of entries) {
    const num = e.number ? `#${e.number}` : '—';
    const cat = e.category ? `[${cell(e.category)}]` : '—';
    out.push(`| ${num} | ${cat} | ${cell(e.title)} | lines ${e.start}-${e.end} |`);
  }
  out.push('', `${entries.length} entries indexed.`, '');
  return out.join('\n');
}

export function main() {
  if (!existsSync(SOURCE)) {
    console.error(`ERROR: lessons source not found: ${SOURCE}\nNext step: run from a checkout that contains docs/LessonsLearned.md.`);
    return 1;
  }
  const entries = parseEntries(readFileSync(SOURCE, 'utf8'));
  mkdirSync(dirname(OUTPUT), { recursive: true });
  writeFileSync(OUTPUT, renderIndex(entries));
  console.log(`Wrote ${OUTPUT} (${entries.length} entries)`);
  return 0;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.exit(main());
}
