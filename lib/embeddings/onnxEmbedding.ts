// ── WordPiece Tokenizer ───────────────────────────────

interface TokenizerJson {
  model: {
    type: string;
    vocab: Record<string, number>;
    unk_token?: string;
    continuing_subword_prefix?: string;
    max_input_chars_per_word?: number;
  };
  normalizer?: { type: string; lowercase?: boolean; strip_accents?: boolean };
  pre_tokenizer?: { type: string };
}

class WordPieceTokenizer {
  private vocab: Map<string, number>;
  private unkToken: string;
  private unkId: number;
  private prefix: string;
  private maxChars: number;
  private clsId: number;
  private sepId: number;
  private padId: number;

  constructor(tokenizerJson: TokenizerJson) {
    this.vocab = new Map(Object.entries(tokenizerJson.model.vocab));
    this.unkToken = tokenizerJson.model.unk_token ?? '[UNK]';
    this.unkId = this.vocab.get(this.unkToken) ?? 0;
    this.prefix = tokenizerJson.model.continuing_subword_prefix ?? '##';
    this.maxChars = tokenizerJson.model.max_input_chars_per_word ?? 100;
    this.clsId = this.vocab.get('[CLS]') ?? 101;
    this.sepId = this.vocab.get('[SEP]') ?? 102;
    this.padId = this.vocab.get('[PAD]') ?? 0;
  }

  /**
   * Tokenize and encode text into input_ids, attention_mask, token_type_ids.
   * Follows BERT tokenization: [CLS] tokens [SEP] with padding to maxLen.
   */
  encode(text: string, maxLen: number = MAX_SEQ_LENGTH): {
    inputIds: number[];
    attentionMask: number[];
    tokenTypeIds: number[];
  } {
    // Normalize: lowercase + basic cleaning
    const normalized = text.toLowerCase().replace(/[\x00-\x1f]+/g, ' ').trim();

    // Pre-tokenize: split on whitespace and punctuation
    const words = this.preTokenize(normalized);

    // WordPiece tokenize each word
    const tokens: number[] = [this.clsId];
    for (const word of words) {
      if (tokens.length >= maxLen - 1) break; // leave room for [SEP]
      const subTokens = this.wordPiece(word);
      for (const t of subTokens) {
        if (tokens.length >= maxLen - 1) break;
        tokens.push(t);
      }
    }
    tokens.push(this.sepId);

    // Pad to maxLen
    const inputIds = new Array(maxLen).fill(this.padId);
    const attentionMask = new Array(maxLen).fill(0);
    const tokenTypeIds = new Array(maxLen).fill(0);

    for (let i = 0; i < tokens.length; i++) {
      inputIds[i] = tokens[i];
      attentionMask[i] = 1;
    }

    return { inputIds, attentionMask, tokenTypeIds };
  }

  private preTokenize(text: string): string[] {
    // Split on whitespace, then separate punctuation
    const words: string[] = [];
    for (const part of text.split(/\s+/)) {
      if (!part) continue;
      // Split punctuation from words but keep them as separate tokens
      let current = '';
      for (const ch of part) {
        if (this.isPunctuation(ch)) {
          if (current) { words.push(current); current = ''; }
          words.push(ch);
        } else {
          current += ch;
        }
      }
      if (current) words.push(current);
    }
    return words;
  }

  private isPunctuation(ch: string): boolean {
    const code = ch.charCodeAt(0);
    // ASCII punctuation ranges
    if ((code >= 33 && code <= 47) || (code >= 58 && code <= 64) ||
        (code >= 91 && code <= 96) || (code >= 123 && code <= 126)) {
      return true;
    }
    // Unicode general punctuation
    if (code >= 0x2000 && code <= 0x206F) return true;
    return false;
  }

  private wordPiece(word: string): number[] {
    if (word.length > this.maxChars) return [this.unkId];

    const tokens: number[] = [];
    let start = 0;

    while (start < word.length) {
      let end = word.length;
      let found = false;

      while (start < end) {
        const substr = start > 0
          ? this.prefix + word.slice(start, end)
          : word.slice(start, end);

        if (this.vocab.has(substr)) {
          tokens.push(this.vocab.get(substr)!);
          found = true;
          break;
        }
        end--;
      }

      if (!found) {
        tokens.push(this.unkId);
        break;
      }
      start = end;
    }

    return tokens;
  }
}

// ── Model Management ──────────────────────────────────

function getModelDir(): string {
  if (_modelDir) return _modelDir;

  // Authoritative baked dir (offline) takes precedence — DevOps bakes the flat model
  // set here (t/1641). When set, the module never touches the network.
  const override = process.env[MODEL_DIR_ENV];
  if (override && override.trim()) {
    _modelDir = override.trim();
    _offline = true;
    return _modelDir;
  }

  // Otherwise check known cache locations, then fall back to the user cache for dev download.
  const candidates = [
    path.join(process.cwd(), '.cache', 'onnx-models', 'all-MiniLM-L6-v2'),
    path.join(process.env.HOME || process.env.USERPROFILE || '', '.cache', 'onnx-models', 'all-MiniLM-L6-v2'),
  ];

  for (const dir of candidates) {
    if (fs.existsSync(path.join(dir, MODEL_FILE))) {
      _modelDir = dir;
      return dir;
    }
  }

  // Default to user cache for downloads
  _modelDir = candidates[candidates.length - 1];
  return _modelDir;
}

function downloadFile(url: string, dest: string): Promise<void> {
  return new Promise((resolve, reject) => {
    fs.mkdirSync(path.dirname(dest), { recursive: true });

    const get = (u: string) => {
      https.get(u, (res) => {
        if ([301, 302, 303, 307, 308].includes(res.statusCode!)) {
          res.resume(); // drain response before following redirect
          const location = res.headers.location;
          if (location) {
            const resolved = location.startsWith('/') ? new URL(location, u).href : location;
            get(resolved);
            return;
          }
        }
        if (res.statusCode !== 200) {
          res.resume();
          reject(new Error(`Download failed: HTTP ${res.statusCode} for ${u}`));
          return;
        }
        const file = fs.createWriteStream(dest);
        res.pipe(file);
        file.on('finish', () => { file.close(); resolve(); });
      }).on('error', reject);
    };
    get(url);
  });
}

async function ensureModelFiles(): Promise<string> {
  const dir = getModelDir();

  // The flat baked set: fp32 model + tokenizer + tokenizer config. Same layout whether
  // the dir is a DevOps-baked offline dir or a dev-downloaded cache.
  const required = [
    { name: MODEL_FILE, url: `${HF_BASE}/${MODEL_FILES.model}`, dest: path.join(dir, MODEL_FILE) },
    { name: TOKENIZER_FILE, url: `${HF_BASE}/${MODEL_FILES.tokenizer}`, dest: path.join(dir, TOKENIZER_FILE) },
    { name: TOKENIZER_CONFIG_FILE, url: `${HF_BASE}/${MODEL_FILES.config}`, dest: path.join(dir, TOKENIZER_CONFIG_FILE) },
  ];

  const missing = required.filter(f => !fs.existsSync(f.dest));

  // Offline short-circuit: all files present → never touch the network.
  if (missing.length === 0) return dir;

  if (_offline) {
    // Authoritative baked dir is incomplete — record + fail, never fall back to HF.
    const missingNames = missing.map(m => m.name).join(', ');
    getGlobalRecorder()?.record({
      type: 'system.error',
      component: 'onnxEmbedding',
      level: 'error',
      message: `Baked ONNX model dir is missing required files: ${missingNames}`,
      data: { dir, env: MODEL_DIR_ENV, missing: missing.map(m => m.name) },
    });
    throw new ActionableError({
      goal: 'Load the baked all-MiniLM-L6-v2 fp32 ONNX model for offline embedding',
      problem: `Model dir "${dir}" (from ${MODEL_DIR_ENV}) is missing: ${missingNames}`,
      location: 'lib/embeddings/onnxEmbedding.ts:ensureModelFiles',
      nextSteps: [
        `Bake the flat model set into ${dir}: ${MODEL_FILE} (fp32), ${TOKENIZER_FILE}, ${TOKENIZER_CONFIG_FILE}`,
        `Or unset ${MODEL_DIR_ENV} to allow on-demand download from Hugging Face in dev`,
      ],
    });
  }

  // Dev mode: download the missing files into the flat cache dir.
  console.log(`[onnxEmbedding] Downloading ${missing.length} model files to ${dir}...`);
  for (const f of missing) {
    console.log(`[onnxEmbedding]   Downloading ${f.name}...`);
    await downloadFile(f.url, f.dest);
    console.log(`[onnxEmbedding]   ${f.name} OK (${(fs.statSync(f.dest).size / 1024 / 1024).toFixed(1)} MB)`);
  }

  return dir;
}

// ── Initialization ────────────────────────────────────

async function init(): Promise<void> {
  // Load onnxruntime-node dynamically (it's a native module).
  // Use createRequire because native addons don't have ESM entry points,
  // and this file compiles as ESM (module: nodenext).
  try {
    const { createRequire } = await import('module');
    const require = createRequire(import.meta.url);
    _ort = require('onnxruntime-node') as OrtModule;
  } catch (err) {
    getGlobalRecorder()?.record({
      type: 'system.error',
      component: 'onnxEmbedding',
      level: 'error',
      message: 'onnxruntime-node native module failed to load',
      data: { error: String(err) },
    });
    throw new ActionableError({
      goal: 'Load the onnxruntime-node native module for in-process embedding',
      problem: `onnxruntime-node could not be required: ${String(err)}`,
      location: 'lib/embeddings/onnxEmbedding.ts:init',
      nextSteps: ['Run: npm install onnxruntime-node', 'Confirm the native addon matches this Node/Electron ABI'],
      innerError: err,
    });
  }

  const dir = await ensureModelFiles();
  const modelPath = path.join(dir, MODEL_FILE);
  const tokenizerPath = path.join(dir, TOKENIZER_FILE);

  // Load tokenizer
  const tokenizerJson = JSON.parse(
    fs.readFileSync(tokenizerPath, 'utf-8'),
  ) as TokenizerJson;
  _tokenizer = new WordPieceTokenizer(tokenizerJson);

  // Determine best execution provider
  const backends = _ort.listSupportedBackends();
  const backendNames = backends.map(b => b.name);
  let executionProviders: string[];

  // t/3198 — opt-in CPU pin. When AI_TRIAD_ONNX_FORCE_CPU is truthy, select the CPU EP regardless
  // of available GPU backends. Default (env unset) is byte-identical to before. Two uses: (1) the
  // real-ONNX equivalence check (onnx-equivalence-check.mjs) must run on the CPU EP — the EP CI and
  // prod (ACA, no GPU) actually use, and the only one where the worker's intra-op=1 is bit-exact vs
  // the in-thread default (a GPU EP is non-deterministic across sessions: ~1e-8 kernel noise, not a
  // real divergence); (2) reproducing prod's CPU-only embedding behavior on a GPU dev box.
  const forceCpuEnv = process.env.AI_TRIAD_ONNX_FORCE_CPU;
  const forceCpu = !!forceCpuEnv && forceCpuEnv !== '0' && forceCpuEnv.toLowerCase() !== 'false';

  if (forceCpu) {
    executionProviders = ['cpu'];
    _selectedEP = 'cpu';
    console.warn(`[onnxEmbedding] CPU EP forced by AI_TRIAD_ONNX_FORCE_CPU=${forceCpuEnv} (skipping GPU backends: ${backendNames.filter(n => n !== 'cpu').join(', ') || 'none'})`);
  } else if (_forcedCpuReason) {
    // t/2060 — a prior non-CPU EP OOM'd during inference; stay pinned to CPU for the
    // rest of the process so we don't re-OOM. Slower but correct.
    executionProviders = ['cpu'];
    _selectedEP = 'cpu';
  } else if (backendNames.includes('openvino')) {
    executionProviders = ['openvino', 'cpu'];
    _selectedEP = 'openvino';
  } else if (backendNames.includes('dml')) {
    executionProviders = ['dml', 'cpu'];
    _selectedEP = 'dml';
  } else {
    executionProviders = ['cpu'];
    _selectedEP = 'cpu';
  }
  console.log(`[onnxEmbedding] Using ${_selectedEP} EP (available: ${backendNames.join(', ')})`);

  // Create session. `_sessionThreadOptions` is EMPTY on the in-thread path, so this reduces to
  // `{ executionProviders }` exactly as before (byte-identical baseline, TL Q3); the worker sets
  // intra/interOp=1 via setSessionThreadOptions() to avoid core oversubscription (C2).
  const t0 = Date.now();
  _session = await _ort.InferenceSession.create(modelPath, { executionProviders, ..._sessionThreadOptions });
  console.log(`[onnxEmbedding] Model loaded in ${Date.now() - t0}ms (${EMBEDDING_DIM}d, fp32, EP=${_selectedEP})`);
}

async function ensureReady(): Promise<void> {
  if (_session && _tokenizer) return;
  if (!_initPromise) {
    _initPromise = init().catch(err => {
      _initPromise = null;
      throw err;
    });
  }
  await _initPromise;
}

// ── Inference ─────────────────────────────────────────

function meanPool(
  lastHidden: Float32Array,
  attentionMask: number[],
  seqLen: number,
  hiddenSize: number,
): Float32Array {
  const result = new Float32Array(hiddenSize);
  let tokenCount = 0;

  for (let i = 0; i < seqLen; i++) {
    if (attentionMask[i] === 0) continue;
    tokenCount++;
    for (let j = 0; j < hiddenSize; j++) {
      result[j] += lastHidden[i * hiddenSize + j];
    }
  }

  if (tokenCount > 0) {
    for (let j = 0; j < hiddenSize; j++) {
      result[j] /= tokenCount;
    }
  }

  return result;
}

function l2Normalize(vec: Float32Array): number[] {
  let norm = 0;
  for (let i = 0; i < vec.length; i++) {
    norm += vec[i] * vec[i];
  }
  norm = Math.sqrt(norm);
  const result = new Array(vec.length);
  if (norm > 0) {
    for (let i = 0; i < vec.length; i++) {
      result[i] = vec[i] / norm;
    }
  } else {
    result.fill(0);
  }
  return result;
}

// ── Public API ────────────────────────────────────────

/**
 * Set extra InferenceSession options applied at session-create time (t/3181 Q3). Used by the
 * off-thread embedding worker to pin ONNX to a single op thread (`{intraOpNumThreads:1,
 * interOpNumThreads:1}`) so it can't oversubscribe the host's 1–2 vCPUs (C2). MUST be called
 * before the first warmup/compute (the session is created once). The in-thread path never calls
 * this, so its create() call stays byte-identical to the pre-t/3181 baseline (equivalence +
 * rollback safety — TL Q3). No effect once the session already exists.
 */
export function setSessionThreadOptions(opts: { intraOpNumThreads?: number; interOpNumThreads?: number }): void {
  _sessionThreadOptions = { ...opts };
}

/**
 * Preload the ONNX model and tokenizer.
 * Call this at startup for faster first inference.
 * Throws if onnxruntime-node is missing or model download fails.
 */
export async function warmup(): Promise<void> {
  await ensureReady();
}

/**
 * Try to initialize the ONNX runtime. Returns true if ready, false if
 * onnxruntime-node is unavailable or model loading fails.
 * Consumers can use this to decide whether to fall back to Python subprocess.
 */
export async function tryWarmup(): Promise<boolean> {
  if (_warmupResult !== null) return _warmupResult;
  try {
    await ensureReady();
    _warmupResult = true;
    _warmupError = undefined;
    return true;
  } catch (err) {
    _warmupResult = false;
    _warmupError = String(err);
    console.warn(`[onnxEmbedding] Initialization failed, Python fallback recommended: ${err}`);
    return false;
  }
}

/** Check if the model is loaded and ready for inference. */
export function isReady(): boolean {
  return _session != null && _tokenizer != null;
}

/** Report cached warmup status for health endpoints. */
export function getWarmupStatus(): { ready: boolean; error?: string } {
  if (_warmupResult === null) return { ready: false, error: 'warmup not yet attempted' };
  return _warmupResult ? { ready: true } : { ready: false, error: _warmupError };
}

/** Return the active execution provider ('openvino', 'dml', 'cpu', or 'none' if not initialized). */
export function getExecutionProvider(): string {
  return _selectedEP;
}

/**
 * Compute a 384-dim embedding for a single text.
 * The model and tokenizer are loaded on first call.
 */
export async function computeEmbedding(text: string): Promise<number[]> {
  await ensureReady();
  const results = await computeEmbeddings([text]);
  return results[0];
}

/**
 * Classify a GPU-EP inference failure that a CPU session can recover from, matched on the thrown
 * message. 'oom' = DirectML / OpenVINO out-of-memory (t/2060). 'device-lost' = the DXGI
 * device-removed family: 887A0005 DEVICE_REMOVED (surfaces as "The GPU device instance has been
 * suspended" after a driver TDR, sleep/resume or driver update), 887A0006 DEVICE_HUNG,
 * 887A0007 DEVICE_RESET, 887A0020 DRIVER_INTERNAL_ERROR. A removed device never comes back for
 * the session that owned it, so without recovery EVERY later call re-throws on the dead session
 * and drops to the per-call Python / Gemini fallbacks (2026-10-03 desktop log).
 */
function classifyGpuFault(err: unknown): 'oom' | 'device-lost' | null {
  const msg = err instanceof Error ? err.message : String(err);
  if (/8007000E|E_OUTOFMEMORY|not enough memory/i.test(msg)) return 'oom';
  if (/887A000[567]|887A0020|DXGI_ERROR_DEVICE_(REMOVED|HUNG|RESET)|device instance has been suspended|GetDeviceRemovedReason/i.test(msg)) {
    return 'device-lost';
  }
  return null;
}

/**
 * Recreate the inference session pinned to the CPU EP after a GPU fault (OOM, t/2060; or a
 * removed/suspended device). Releases
 * the faulted session and re-inits; `_forcedCpuReason` (set by the caller) makes init()
 * select `['cpu']`, so this — and every subsequent call for the process lifetime — runs
 * on CPU and can't re-OOM.
 */
async function recreateSessionOnCpu(): Promise<void> {
  try {
    await _session?.release();
  } catch {
    /* telemetry — silent by design: releasing an already-faulted GPU session may itself
       throw; the recreate below is what matters, and the OOM is recorded by the caller. */
  }
  _session = null;
  _initPromise = null;
  await ensureReady();
}

/**
 * Run one chunk's inference, falling back from a GPU EP to CPU on a GPU fault (t/2060).
 * onnxruntime does NOT gracefully fall a failing op back to CPU — a mid-inference DML
 * OOM (8007000E) or removed device (887A0005) throws — so catch it, pin CPU for the process,
 * recreate the session on CPU, and retry ONCE. Any other error, a fault already on CPU, or a
 * CPU-retry failure is terminal (no further fallback). Generalized to ANY non-CPU EP
 * (dml/openvino) per TL t/2060#4.
 */
async function runInferenceWithCpuFallback(
  feeds: Record<string, OrtTensor>,
): Promise<Record<string, OrtTensor>> {
  try {
    return await _session!.run(feeds);
  } catch (err) {
    const fault = classifyGpuFault(err);
    if (!fault || _selectedEP === 'cpu') throw err;
    const prevEP = _selectedEP;
    const what = fault === 'oom' ? 'a GPU OOM (8007000E)' : 'a removed/suspended GPU device (DXGI 887A00xx)';
    getGlobalRecorder()?.record({
      type: 'system.error',
      component: 'onnx-embedding',
      level: 'warn',
      message: `${prevEP} EP hit ${what} during inference — pinning CPU for the process and retrying`,
      data: { prevEP, fault, chunkSize: CHUNK_SIZE, error: (err instanceof Error ? err.message : String(err)).slice(0, 300) },
    });
    console.warn(`[onnxEmbedding] ${prevEP} EP hit ${what} — recreating session on CPU and retrying (slower but correct)`);
    _forcedCpuReason = `${prevEP} EP ${fault} during inference`;
    await recreateSessionOnCpu();
    return await _session!.run(feeds); // retry once on CPU; a further failure is terminal
  }
}

/**
 * Compute 384-dim embeddings for a batch of texts.
 *
 * The batch is processed in sub-batches of CHUNK_SIZE (t/2060): a single large
 * `session.run` builds one massive GPU tensor that OOMs DirectML (8007000E) even for a
 * few hundred nodes, so chunking bounds peak VRAM per forward pass. Results are
 * concatenated in the original input order. Each chunk's run carries a GPU→CPU OOM
 * fallback (see runInferenceWithCpuFallback).
 */
export async function computeEmbeddings(
  texts: string[],
  onChunkDone?: (chunkIndex: number) => void,
): Promise<number[][]> {
  // t/716: refuse a non-string text here, naming the element, before it reaches the tokenizer.
  assertEmbeddingTexts(texts, 'lib/embeddings/onnxEmbedding.ts:computeEmbeddings');
  await ensureReady();
  if (texts.length === 0) return [];

  // `onChunkDone` (t/3181) fires after each chunk RESOLVES — the off-thread worker uses it to emit
  // a forward-progress heartbeat to its watchdog (a healthy-but-slow large batch keeps heartbeating;
  // a truly wedged worker stops within ~1 chunk). Optional; in-thread callers omit it → no behavior
  // change. It signals completed progress only, never gates or reorders compute.
  const results: number[][] = [];
  let chunkIndex = 0;
  for (let start = 0; start < texts.length; start += CHUNK_SIZE) {
    const chunkResults = await computeChunk(texts.slice(start, start + CHUNK_SIZE));
    results.push(...chunkResults);
    onChunkDone?.(chunkIndex++);
  }
  return results;
}

/** Embed a single sub-batch (≤ CHUNK_SIZE texts) in one forward pass. */
async function computeChunk(texts: string[]): Promise<number[][]> {
  const ort = _ort!;
  const tokenizer = _tokenizer!;

  const batchSize = texts.length;
  const seqLen = MAX_SEQ_LENGTH;

  // Tokenize all texts in the chunk
  const allInputIds = new BigInt64Array(batchSize * seqLen);
  const allAttentionMask = new BigInt64Array(batchSize * seqLen);
  const allTokenTypeIds = new BigInt64Array(batchSize * seqLen);
  const masks: number[][] = [];

  for (let b = 0; b < batchSize; b++) {
    const { inputIds, attentionMask, tokenTypeIds } = tokenizer.encode(texts[b], seqLen);
    masks.push(attentionMask);
    const offset = b * seqLen;
    for (let i = 0; i < seqLen; i++) {
      allInputIds[offset + i] = BigInt(inputIds[i]);
      allAttentionMask[offset + i] = BigInt(attentionMask[i]);
      allTokenTypeIds[offset + i] = BigInt(tokenTypeIds[i]);
    }
  }

  // Create tensors
  const feeds: Record<string, OrtTensor> = {
    input_ids: new ort.Tensor('int64', allInputIds, [batchSize, seqLen]),
    attention_mask: new ort.Tensor('int64', allAttentionMask, [batchSize, seqLen]),
    token_type_ids: new ort.Tensor('int64', allTokenTypeIds, [batchSize, seqLen]),
  };

  // Run inference (GPU→CPU OOM fallback per t/2060)
  const output = await runInferenceWithCpuFallback(feeds);

  // Extract last_hidden_state (or the first output)
  const outputKey = Object.keys(output)[0];
  const hiddenState = output[outputKey];
  const hiddenData = hiddenState.data as Float32Array;
  const hiddenSize = hiddenState.dims[hiddenState.dims.length - 1];

  // Mean pool + normalize each item in the chunk
  const results: number[][] = [];
  for (let b = 0; b < batchSize; b++) {
    const offset = b * seqLen * hiddenSize;
    const slice = hiddenData.subarray(offset, offset + seqLen * hiddenSize);
    const pooled = meanPool(slice, masks[b], seqLen, hiddenSize);
    results.push(l2Normalize(pooled));
  }

  return results;
}

/** Release the ONNX session. Call on app shutdown. */
export async function dispose(): Promise<void> {
  if (_session) {
    await _session.release();
    _session = null;
  }
  _tokenizer = null;
  _initPromise = null;
}
