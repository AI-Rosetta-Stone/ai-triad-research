<#
.SYNOPSIS
    Rotates one sign-in client secret (Microsoft/AAD, Google, or GitHub), writing the GitHub
    Actions secret and the container-app secret together, and refuses to delete the old
    credential until BOTH the new one is confirmed present AND a sign-in has been confirmed
    working.
.DESCRIPTION
    t/4288 (2026-10-19): two outages from manual, un-sequenced secret rotation.
      1. A container-secret-only change was silently reverted by the next deploy, because
         deploys always re-apply AAD_CLIENT_SECRET from GitHub (the deploy's source wins).
      2. The follow-up rotation deleted the old Entra credential BEFORE the new one had
         finished propagating, leaving a window with zero valid credentials.
    This script closes both gaps by construction:
      - Phase 1 always writes the GitHub secret AND the container secret in the same run,
        never one alone.
      - Phase 2 (deletion) runs ONLY after an explicit, separate confirmation step, and
        HARD-REFUSES if the new credential isn't visible in `az ad app credential list` or
        the operator hasn't typed the sign-in confirmation phrase.
    For AAD, the new credential's VALUE is generated by Azure (`az ad app credential reset`)
    and is never displayed — it's piped directly into `gh secret set` and
    `az containerapp secret set`, matching the no-value-printing-secret-commands rule (t/4288).
    For Google/GitHub OAuth secrets (generated in their own consoles, not Azure), pass
    -NewSecretValue as a SecureString; the script still never writes it to the console.
.PARAMETER Provider
    'aad' | 'google' | 'github' — which sign-in secret to rotate.
.PARAMETER NewSecretValue
    Required for Google/GitHub (the new value from that provider's console). Omit for AAD —
    the script generates it via `az ad app credential reset` and never displays it.
.PARAMETER AadAppId
    The Entra app registration's appId. Required when -Provider aad.
.PARAMETER ResourceGroup
    Azure resource group. Default: ai-triad.
.PARAMETER ContainerAppName
    Azure Container App name. Default: taxonomy-editor.
.PARAMETER SkipDelete
    Writes the new secret and restarts, but stops before the deletion phase — use this to
    rotate without immediately retiring the old credential (e.g. a scheduled rotation where
    the old one isn't known-bad yet).
.EXAMPLE
    ./Rotate-SignInSecret.ps1 -Provider aad -AadAppId 51dee973-5497-47f8-a749-68603cbe8c8f
.EXAMPLE
    ./Rotate-SignInSecret.ps1 -Provider google -NewSecretValue (Read-Host -AsSecureString 'New Google client secret')
#>
[CmdletBinding(SupportsShouldProcess)]
param(
    [Parameter(Mandatory)]
    [ValidateSet('aad', 'google', 'github')]
    [string]$Provider,

    [System.Security.SecureString]$NewSecretValue,

    [string]$AadAppId,

    [string]$ResourceGroup = 'ai-triad',

    [string]$ContainerAppName = 'taxonomy-editor',

    [switch]$SkipDelete
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

function New-ActionableError {
    param([string]$Goal, [string]$Problem, [string]$Location, [string]$NextSteps)
    "Goal: $Goal`nProblem: $Problem`nLocation: $Location`nResolve: $NextSteps"
}

$providerMap = @{
    aad    = @{ GitHubSecret = 'AAD_CLIENT_SECRET'; ContainerSecret = 'aad-client-secret'; DisplayName = 'Microsoft (AAD)' }
    google = @{ GitHubSecret = 'GOOGLE_CLIENT_SECRET'; ContainerSecret = 'google-client-secret'; DisplayName = 'Google' }
    github = @{ GitHubSecret = 'GITHUB_CLIENT_SECRET'; ContainerSecret = 'github-client-secret'; DisplayName = 'GitHub' }
}
$cfg = $providerMap[$Provider]

if ($Provider -eq 'aad' -and -not $AadAppId) {
    throw (New-ActionableError -Goal 'Rotate the Microsoft sign-in secret' `
        -Problem '-AadAppId was not supplied' `
        -Location 'Rotate-SignInSecret.ps1 -Provider aad' `
        -NextSteps 'Pass -AadAppId <the Entra app registration appId>, e.g. 51dee973-5497-47f8-a749-68603cbe8c8f')
}
if ($Provider -ne 'aad' -and -not $NewSecretValue) {
    throw (New-ActionableError -Goal "Rotate the $($cfg.DisplayName) sign-in secret" `
        -Problem '-NewSecretValue was not supplied' `
        -Location "Rotate-SignInSecret.ps1 -Provider $Provider" `
        -NextSteps "Generate a new client secret in $($cfg.DisplayName)'s own console first, then pass it as -NewSecretValue (SecureString).")
}

Write-Host "=== Rotating $($cfg.DisplayName) sign-in secret ===" -ForegroundColor Cyan
Write-Host "Before you continue: ping the Computational Linguist — the revision restart at the end of this script will kill any in-flight inquiry (t/4288 lesson)." -ForegroundColor Yellow

# ── Phase 1: generate/obtain the new value, write BOTH copies, restart ──────────────────
$plainValue = $null
$oldKeyId = $null

if ($Provider -eq 'aad') {
    $newDisplayName = "easyauth-$(Get-Date -Format 'yyyy-MM-dd')"
    if ($PSCmdlet.ShouldProcess($AadAppId, "az ad app credential reset (new credential: $newDisplayName)")) {
        # The value is captured straight into a variable and never echoed — `reset` prints it
        # to stdout by default, so we request JSON and read the field, never -o tsv to a
        # terminal. Still never Write-Host $credResult.password anywhere below.
        $credResultJson = az ad app credential reset --id $AadAppId --display-name $newDisplayName --years 1 --query '{password:password}' -o json 2>$null
        if ($LASTEXITCODE -ne 0 -or -not $credResultJson) {
            throw (New-ActionableError -Goal 'Create a new Entra client-secret credential' `
                -Problem 'az ad app credential reset failed or returned nothing' `
                -Location "Rotate-SignInSecret.ps1, az ad app credential reset --id $AadAppId" `
                -NextSteps 'Confirm the appId is correct and the caller has Application.ReadWrite.OwnedBy (or equivalent) on this app registration.')
        }
        $credResult = $credResultJson | ConvertFrom-Json
        $plainValue = $credResult.password
    }
} else {
    $bstr = [System.Runtime.InteropServices.Marshal]::SecureStringToBSTR($NewSecretValue)
    try { $plainValue = [System.Runtime.InteropServices.Marshal]::PtrToStringBSTR($bstr) }
    finally { [System.Runtime.InteropServices.Marshal]::ZeroFreeBSTR($bstr) }
}

if ($PSCmdlet.ShouldProcess('GitHub + Azure Container Apps', "write $($cfg.GitHubSecret) / $($cfg.ContainerSecret)")) {
    # GitHub secret first (t/4288 ordering: so the NEXT ordinary deploy doesn't silently revert
    # a container-only change, same root cause as the 10-19 incident).
    $plainValue | gh secret set $cfg.GitHubSecret -R AI-Rosetta-Stone/ai-triad-research 2>&1 | Out-Null
    if ($LASTEXITCODE -ne 0) {
        throw (New-ActionableError -Goal 'Write the GitHub Actions secret' `
            -Problem "gh secret set $($cfg.GitHubSecret) failed (exit $LASTEXITCODE)" `
            -Location 'Rotate-SignInSecret.ps1, Phase 1' `
            -NextSteps 'Check gh auth status and repo write access, then re-run.')
    }

    az containerapp secret set -n $ContainerAppName -g $ResourceGroup --secrets "$($cfg.ContainerSecret)=$plainValue" 2>&1 | Out-Null
    if ($LASTEXITCODE -ne 0) {
        throw (New-ActionableError -Goal 'Write the Azure Container App secret' `
            -Problem "az containerapp secret set failed (exit $LASTEXITCODE)" `
            -Location 'Rotate-SignInSecret.ps1, Phase 1' `
            -NextSteps "The GitHub secret ($($cfg.GitHubSecret)) was already updated — the two copies are now OUT OF SYNC. Re-run 'az containerapp secret set' by hand with the same value before doing anything else.")
    }

    Write-Host "Both copies written. Restarting the active revision..." -ForegroundColor Cyan
    $activeRevision = az containerapp revision list -n $ContainerAppName -g $ResourceGroup --query "[?properties.trafficWeight==\`100\`].name" -o tsv
    az containerapp revision restart -n $ContainerAppName -g $ResourceGroup --revision $activeRevision 2>&1 | Out-Null
}
$plainValue = $null  # drop the in-memory copy now that both writes are done

# ── Phase 2: HARD gate — verify new credential exists AND sign-in is confirmed, before any delete ──
if ($SkipDelete) {
    Write-Host "-SkipDelete set: rotation complete, no old credential removed. Re-run without -SkipDelete once you've confirmed sign-in works." -ForegroundColor Yellow
    return
}

Write-Host "`n=== Phase 2: pre-deletion verification (t/4288 — never delete before this passes) ===" -ForegroundColor Cyan

if ($Provider -eq 'aad') {
    $creds = az ad app credential list --id $AadAppId --query "[].{name:customKeyIdentifier,hint:hint,keyId:keyId}" -o json | ConvertFrom-Json
    $newCred = @($creds | Where-Object { $_.name -eq $newDisplayName })
    if (@($newCred).Count -eq 0) {
        throw (New-ActionableError -Goal 'Verify the new credential exists before deleting anything' `
            -Problem "az ad app credential list does not show '$newDisplayName' yet" `
            -Location 'Rotate-SignInSecret.ps1, Phase 2' `
            -NextSteps 'Do NOT delete the old credential. Wait and re-check — Entra propagation can lag a few minutes — or re-run Phase 1.')
    }
    Write-Host "Confirmed: '$newDisplayName' (hint $($newCred[0].hint)) is listed on the app registration." -ForegroundColor Green
}

Write-Host "`nBefore anything is deleted: go test a $($cfg.DisplayName) sign-in against the live app right now." -ForegroundColor Yellow
$confirmation = Read-Host "Type the exact phrase 'sign-in confirmed' to proceed to deletion, or anything else to stop here"
if ($confirmation -ne 'sign-in confirmed') {
    Write-Host "Stopping before deletion — nothing old was removed. The new secret is live in both copies; re-run with -SkipDelete:`$false once sign-in is confirmed, or just run Phase 2 again." -ForegroundColor Yellow
    return
}

if ($Provider -eq 'aad') {
    $oldCreds = @($creds | Where-Object { $_.name -ne $newDisplayName })
    foreach ($old in $oldCreds) {
        if ($PSCmdlet.ShouldProcess($AadAppId, "az ad app credential delete --key-id $($old.keyId) (was '$($old.name)', hint $($old.hint))")) {
            az ad app credential delete --id $AadAppId --key-id $old.keyId 2>&1 | Out-Null
            if ($LASTEXITCODE -ne 0) {
                Write-Warning "Failed to delete credential keyId $($old.keyId) (hint $($old.hint)) — remove it by hand."
            } else {
                Write-Host "Deleted old credential (hint $($old.hint))." -ForegroundColor Green
            }
        }
    }
} else {
    Write-Host "$($cfg.DisplayName) client secrets aren't Entra credentials with a list/delete API — retire the old one in $($cfg.DisplayName)'s own console once you're ready." -ForegroundColor Yellow
}

Write-Host "`nRotation complete." -ForegroundColor Green
