// Writes t0-rule-order.fixture.json: what a given copy of t0-enqueue-sweep.mjs decides for every
// case in t0-rule-order.cases.mjs. t0-rule-order.test.mjs then holds the working tree's
// selectT0Candidates to that file.
//
// Run it against a copy that is KNOWN to have the rule order you want to keep (main's, before a
// refactor), never against the code under test: a fixture regenerated from the refactored code
// proves nothing. The fixture records the commit and blob it was generated from.
//
//   node operations/devops/gen-t0-rule-order-fixture.mjs <path/to/reference/t0-enqueue-sweep.mjs> [<out.json>]
//
// The reference file must be committed and unmodified in its own checkout, so the recorded commit
// really names its content.

import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { MUTATORS, EXPECTED_CASE_COUNT, NOW_MS, runCases } from './t0-rule-order.cases.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
export const FIXTURE_PATH = path.join(here, 't0-rule-order.fixture.json');

function fail(problem, nextSteps) {
  return new Error(
    `gen-t0-rule-order-fixture: ${problem}\n` +
    '  Goal:       record the reference T0 rule order as a fixture.\n' +
    `  Problem:    ${problem}\n` +
    '  Location:   operations/devops/gen-t0-rule-order-fixture.mjs\n' +
    `  Next steps: ${nextSteps}`,
  );
}

const git = (cwd, args) => execFileSync('git', ['-C', cwd, ...args], { encoding: 'utf8' }).trim();

/** One case per line, so a changed decision is a one-line diff. */
export function formatFixture({ generatedFrom, cases }) {
  const head = {
    comment: 'GENERATED by operations/devops/gen-t0-rule-order-fixture.mjs from the reference copy named in generatedFrom. ' +
      'Do not edit by hand, and do not regenerate from the code under test (see t0-rule-order.test.mjs).',
    generatedFrom,
    nowMs: NOW_MS,
    mutators: MUTATORS.map((m) => m.id),
    caseCount: cases.length,
  };
  const headJson = JSON.stringify(head, null, 2);
  return `${headJson.slice(0, -2)},\n  "cases": [\n${cases.map((c) => `    ${JSON.stringify(c)}`).join(',\n')}\n  ]\n}\n`;
}

async function main(argv) {
  const [refArg, outArg] = argv;
  if (!refArg) throw fail('no reference module given.', 'pass the path to the reference t0-enqueue-sweep.mjs (main\'s copy).');
  const refPath = path.resolve(refArg);
  const refDir = path.dirname(refPath);

  let commit;
  let blob;
  let relPath;
  try {
    const dirty = git(refDir, ['status', '--porcelain', '--', refPath]);
    if (dirty) throw fail(`the reference file is modified or untracked in its checkout (${dirty}).`, 'commit or restore it, then run again.');
    commit = git(refDir, ['rev-parse', 'HEAD']);
    blob = git(refDir, ['hash-object', refPath]);
    relPath = git(refDir, ['ls-files', '--full-name', '--', refPath]);
    if (!relPath) throw fail(`${refPath} is not tracked by git.`, 'point at a committed copy of t0-enqueue-sweep.mjs.');
    const committedBlob = git(refDir, ['rev-parse', `HEAD:${relPath}`]);
    if (committedBlob !== blob) throw fail(`the reference file's content (${blob}) is not what its HEAD commit holds (${committedBlob}).`, 'restore it, then run again.');
  } catch (err) {
    if (String(err.message).startsWith('gen-t0-rule-order-fixture:')) throw err;
    throw fail(`could not read git facts for ${refPath} (${String(err.message).split('\n')[0]}).`, 'run it on a file inside a git checkout.');
  }

  const { selectT0Candidates } = await import(pathToFileURL(refPath).href);
  if (typeof selectT0Candidates !== 'function') throw fail(`${refPath} does not export selectT0Candidates.`, 'point at a t0-enqueue-sweep.mjs.');
  const cases = runCases(selectT0Candidates);

  // A mutator that does not trip its own rule on the reference is a bug in the cases, not a result.
  const byId = new Map(cases.map((c) => [c.id, c]));
  if (cases.length !== EXPECTED_CASE_COUNT) throw fail(`${cases.length} cases, expected ${EXPECTED_CASE_COUNT}.`, 'fix buildCases in t0-rule-order.cases.mjs.');
  if (!byId.get('base').enqueued) throw fail(`the base PR is not enqueued by the reference (${byId.get('base').reason}).`, 'fix basePr in t0-rule-order.cases.mjs.');
  for (const m of MUTATORS) {
    const c = byId.get(m.id);
    if (c.enqueued || !m.wins.test(c.reason ?? '')) {
      throw fail(`mutator ${m.id} alone gives ${c.enqueued ? 'an enqueue' : JSON.stringify(c.reason)}, not a skip matching ${m.wins}.`, 'fix that mutator in t0-rule-order.cases.mjs.');
    }
  }

  const outPath = outArg ? path.resolve(outArg) : FIXTURE_PATH;
  writeFileSync(outPath, formatFixture({ generatedFrom: { commit, path: relPath, blob }, cases }));
  console.log(`wrote ${cases.length} cases (${MUTATORS.length} mutators) to ${outPath}, from ${relPath} at ${commit} (blob ${blob})`);
}

const isCliEntry = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isCliEntry) {
  main(process.argv.slice(2)).then(
    () => {},
    (err) => { console.error(err.message ?? err); process.exit(1); },
  );
}
