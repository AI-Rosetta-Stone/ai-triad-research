#Requires -Module Pester

<#
.SYNOPSIS
    t/4876 (CL spec t/4876#1): the mechanical participant-attribution post-check. Fixtures are drawn
    verbatim from CL's calibration comment (t/4876#1): 3 known participant-sourced findings (must be
    caught) and 2 "participants as subject" negatives from the same pool (must not be caught).
#>

BeforeAll {
    $ModulePath = Join-Path $PSScriptRoot '..' 'scripts' 'AITriad' 'AITriad.psm1'
    Import-Module $ModulePath -Force -WarningAction SilentlyContinue
}

Describe 'Test-ParticipantAttributionConstruction (t/4876#1 regex family)' -Tag 'unit' {

    It 'catches "In the views of the participants that emerged from the elicitation..."' {
        InModuleScope AITriad {
            Test-ParticipantAttributionConstruction -Text 'In the views of the participants that emerged from the elicitation, the proposed timeline was unrealistic.' |
                Should -Not -BeNullOrEmpty
        }
    }

    It 'catches "Participants became more skeptical..."' {
        InModuleScope AITriad {
            Test-ParticipantAttributionConstruction -Text 'Participants became more skeptical of the proposed framework as the study progressed.' |
                Should -Not -BeNullOrEmpty
        }
    }

    It 'catches "...participants from the online Delphi elicitation did not convey strong optimism..."' {
        InModuleScope AITriad {
            Test-ParticipantAttributionConstruction -Text 'In general, participants from the online Delphi elicitation did not convey strong optimism about near-term adoption.' |
                Should -Not -BeNullOrEmpty
        }
    }

    It 'does not catch participants as the subject of a method recommendation ("Backcasting... can help participants overcome...")' {
        InModuleScope AITriad {
            Test-ParticipantAttributionConstruction -Text 'Backcasting from a desired future state can help participants overcome present-bias in scenario planning.' |
                Should -BeNullOrEmpty
        }
    }

    It 'does not catch participants as the subject of a method recommendation ("...scenarios generated by participants...")' {
        InModuleScope AITriad {
            Test-ParticipantAttributionConstruction -Text 'The workshop began with scenarios generated by participants in small breakout groups.' |
                Should -BeNullOrEmpty
        }
    }

    It 'returns null for empty or whitespace text' {
        InModuleScope AITriad {
            Test-ParticipantAttributionConstruction -Text ''    | Should -BeNullOrEmpty
            Test-ParticipantAttributionConstruction -Text '   ' | Should -BeNullOrEmpty
            Test-ParticipantAttributionConstruction -Text $null | Should -BeNullOrEmpty
        }
    }

    It 'does not false-positive on a plain mention of "respondents" with no view/finding verb' {
        InModuleScope AITriad {
            Test-ParticipantAttributionConstruction -Text 'The survey instrument was sent to 40 respondents across three regions.' |
                Should -BeNullOrEmpty
        }
    }
}
